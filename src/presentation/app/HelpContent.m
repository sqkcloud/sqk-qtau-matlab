        function html = bodyBlock(raw, codeBg) %#ok<INUSD>
            % bodyBlock  Convert a multi-line text block into HTML. Lines
            %   beginning with "•" or "-" become list items; everything
            %   else becomes paragraph text. Indented continuations are
            %   folded onto the previous list item.
            %
            %   Empty-state convention: a single line that starts with an
            %   em-dash ("— Not applicable." etc.) is rendered as a muted
            %   italic note instead of a paragraph — cleaner than the
            %   raw em-dash + sentence on a regular line.
            %
            %   Formula blocks (bullet lines containing one of "=", "∝",
            %   "≈", "≥", "≤", or a leading variable-name colon like
            %   "Distance:") drop the bullet dot and render each item as
            %   a rounded monospace card.
            txt = char(raw);
            if isempty(strtrim(txt)); html = ''; return; end
            esc = @(s) HelpContent.htmlEscape(s);

            % Empty-state shortcut: single-line em-dash note.
            trimmed = strtrim(txt);
            if ~contains(trimmed, newline) && (startsWith(trimmed, char(8212)) ...
                    || startsWith(trimmed, char(8211)) || startsWith(trimmed, '-'))
                stripped = strtrim(regexprep(trimmed, '^[—–\-]\s*', ''));
                html = sprintf('<p class="empty">%s</p>', esc(stripped));
                return;
            end

            lines = regexp(txt, '\r?\n', 'split');

            % Detect whether this block is a formula block by scanning
            % bullet lines for math glyphs.
            isFormulaBlock = false;
            for i = 1:numel(lines)
                t = strtrim(lines{i});
                if (startsWith(t, '•') || startsWith(t, '-')) && ...
                        (contains(t, '=') || contains(t, '∝') ...
                        || contains(t, '≈') || contains(t, '≥') || contains(t, '≤'))
                    isFormulaBlock = true; break;
                end
            end

            html = '';
            inList = false;
            buf = '';
            ulOpen = '';
            for i = 1:numel(lines)
                raw_i = lines{i};
                t = strtrim(raw_i);
                if startsWith(t, '•') || startsWith(t, '-')
                    if ~isempty(strtrim(buf))
                        html = [html '<p>' esc(buf) '</p>']; buf = ''; %#ok<AGROW>
                    end
                    if ~inList
                        if isFormulaBlock
                            ulOpen = '<ul class="formula-list">';
                        else
                            ulOpen = '<ul>';
                        end
                        html = [html ulOpen]; inList = true; %#ok<AGROW>
                    end
                    item = strtrim(t(2:end));
                    if isFormulaBlock
                        html = [html sprintf('<li><div class="formula">%s</div></li>', esc(item))]; %#ok<AGROW>
                    else
                        html = [html sprintf('<li>%s</li>', esc(item))]; %#ok<AGROW>
                    end
                elseif startsWith(raw_i, ' ') && inList && ~isempty(t)
                    % Indented continuation of the previous list item.
                    if isFormulaBlock
                        % Continue inside the most recent .formula div by
                        % stripping its trailing close + re-opening.
                        html = regexprep(html, '</div></li>$', '');
                        html = [html sprintf('<br/>%s</div></li>', esc(t))]; %#ok<AGROW>
                    else
                        html = regexprep(html, '</li>$', '');
                        html = [html ' ' esc(t) '</li>']; %#ok<AGROW>
                    end
                else
                    if inList
                        html = [html '</ul>']; inList = false; %#ok<AGROW>
                    end
                    if isempty(t)
                        if ~isempty(strtrim(buf))
                            html = [html '<p>' esc(buf) '</p>']; buf = ''; %#ok<AGROW>
                        end
                    else
                        if isempty(buf); buf = t; else; buf = [buf ' ' t]; end %#ok<AGROW>
                    end
                end
            end
            if inList; html = [html '</ul>']; end
            if ~isempty(strtrim(buf)); html = [html '<p>' esc(buf) '</p>']; end
        end

        function s = htmlEscape(s)
            if isempty(s); s = ''; return; end
            s = char(s);
            s = strrep(s, '&', '&amp;');
            s = strrep(s, '<', '&lt;');
            s = strrep(s, '>', '&gt;');
        end

        function lbl = getLabel(labels, field, defaultLbl)
            % getLabel  Pull labels.<field> if present + non-empty; fall
            %   back to defaultLbl otherwise. Used by renderHtml to let
            %   the app-level dialog override per-section header text
            %   without breaking the 22 existing screen-level callers
            %   that pass no labels at all.
            if isstruct(labels) && isfield(labels, field) ...
                    && ~isempty(labels.(field))
                lbl = char(labels.(field));
            else
                lbl = defaultLbl;
            end
        end

        function h = toHex(rgb)
            % toHex  RGB triple in [0..1] → #RRGGBB string.
            try
                r = max(0, min(255, round(rgb(1) * 255)));
                g = max(0, min(255, round(rgb(2) * 255)));
                b = max(0, min(255, round(rgb(3) * 255)));
                h = sprintf('#%02X%02X%02X', r, g, b);
            catch
                h = '#262B33';
            end
        end

